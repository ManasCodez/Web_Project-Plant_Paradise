const mongoose = require('mongoose');
module.exports = mongoose.model('ShopProduct', new mongoose.Schema({
  slug: { type: String, required: true, unique: true },
  name: { type: String, required: true },
  description: String,
  shortDescription: String,
  detailedDescription: String,
  scientificName: String,
  famousFor: String,
  uses: String,
  benefits: String,
  careInstructions: String,
  images: [{ _id: false, url: String, publicId: String, alt: String }],
  discountPrice: { type: Number, min: 0, default: null },
  stock: { type: Number, min: 0, default: 0, validate: Number.isInteger },
  availability: { type: String, enum: ['available', 'unavailable'], default: 'available' },
  status: { type: String, enum: ['active', 'draft', 'archived'], default: 'active' },
  showInShop: { type: Boolean, default: true },
  showInCategories: { type: Boolean, default: true },
  cmsVersion: Number,
  imageUrl: String,
  imageAlt: String,
  price: { type: Number, required: true, min: 0 },
  category: { type: String, required: true, index: true },
  displayOrder: { type: Number, default: 0, min: 0 },
}, { timestamps: true, bufferCommands: false }));
